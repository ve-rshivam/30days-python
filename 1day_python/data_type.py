print(type(10))                                 # integer
print(type(11.34))                              # float     
print(type(3.14))                               # float
print(type(4 - 4j))                             # complex
print(type(['Shivam', 'Python', 'India']))      # list
print(type('Shivam'))                           # string
print(type({'JS' : 'Atom', 'CS' : 'VS','Python' : ['Pycharm', 'Sublime'], 'JAVA' : {'JSE' : 'Netbeans', 'JEE' : 'Eclipse'}}))     #  dictionary
print(type({25, 14 ,98 , 63, 75, 98}))          # set
print(type(True))                               # boolean
print(type(False))                              # boolean
print(type((21, 36, 14, 25)))                   # tuple
print(type(None))                               # None type 