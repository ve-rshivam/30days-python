x = int(input("Enter 1st number: "))
y = int(input("Enter 2nd number: "))

# Arthematic Operation:
sum = x + y                     # addition
sub = x - y                     # subtraction
multiplication = x * y          # multiplication
div = x / y                     # division
mod = x % y                     # modulus
expo = x ** y                   # exponential
floor = x // y                  # floor division operator
print("Addition:",sum)
print("Subtraction:",sub)
print("Multiplication:",multiplication)
print("Division:",div)
print("Modulus:",mod)
print("Exponential:",expo)
print("Floor Division Operator:",floor)  # Floor division (//) drops the decimal and returns an integer