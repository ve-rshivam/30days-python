# Does 'Coding For All' start with a substring Coding?
# Does 'Coding For All' end with a substring coding?
# '   Coding For All      '  , remove the left and right trailing spaces in the given string.

substring = 'Coding For All'

print(substring.startswith('Coding'))           # it's check that string present in starting
print(substring.endswith('Coding'))             # it's check that string present in last
print(substring.strip())                        # it can remove all the space from starting and ending